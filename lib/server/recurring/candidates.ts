import { and, eq, gte, lte } from "drizzle-orm";

import { creditCardCharges, recurringOccurrenceLinks, transactions } from "@/lib/db/schema";
import type { FinanceDatabase } from "@/lib/interfaces/database";
import type { RecurringMatchCandidate } from "@/lib/interfaces/recurring-occurrences";
import { recurringCandidateWindow } from "@/lib/recurring-matching";
import { listSettlementTransactionIds } from "@/lib/server/transactions/settlement-ids";

type LinkRow = typeof recurringOccurrenceLinks.$inferSelect;

export function linkEntryId(link: Pick<LinkRow, "transactionId" | "creditCardChargeId">) {
  return (link.transactionId ?? link.creditCardChargeId) as string;
}

export async function listOccurrenceLinks(db: FinanceDatabase): Promise<LinkRow[]> {
  return db.query.recurringOccurrenceLinks.findMany();
}

/**
 * Entries of the window around `month` that may pay a rule: income, expenses and contributions that are not cancelled,
 * not generated by a rule, not a card bill payment nor part of an investment funding, plus single card purchases.
 */
export async function listRecurringMatchCandidates(db: FinanceDatabase, month: string): Promise<RecurringMatchCandidate[]> {
  const window = recurringCandidateWindow(month);
  const [rows, charges, excluded] = await Promise.all([
    db.query.transactions.findMany({
      where: and(gte(transactions.transactionDate, window.start), lte(transactions.transactionDate, window.end)),
      with: { account: true, category: true },
    }),
    db.query.creditCardCharges.findMany({
      where: and(eq(creditCardCharges.kind, "purchase"), gte(creditCardCharges.purchaseDate, window.start), lte(creditCardCharges.purchaseDate, window.end)),
      with: { account: true, category: true },
    }),
    listSettlementTransactionIds(db, { withdrawals: true }),
  ]);
  const ledger = rows
    .filter((row) => row.status !== "cancelled" && !row.recurringTemplateId && !excluded.has(row.id) && row.type !== "investment_withdrawal" && row.account?.type !== "credit")
    .map((row): RecurringMatchCandidate => ({
      id: row.id,
      kind: "transaction",
      type: row.type,
      categoryId: row.categoryId,
      categoryName: row.category?.name ?? null,
      amountCents: row.amountCents,
      date: row.transactionDate,
      description: row.description,
      accountName: row.account?.name ?? null,
    }));
  const card = charges
    .filter((charge) => charge.installmentCount === 1 && charge.totalAmountCents > 0)
    .map((charge): RecurringMatchCandidate => ({
      id: charge.id,
      kind: "card",
      type: "expense",
      categoryId: charge.categoryId,
      categoryName: charge.category?.name ?? null,
      amountCents: charge.totalAmountCents,
      date: charge.purchaseDate,
      description: charge.description,
      accountName: charge.account?.name ?? null,
    }));
  return [...ledger, ...card].sort((left, right) => left.date.localeCompare(right.date) || left.id.localeCompare(right.id));
}
